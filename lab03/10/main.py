# Неявное преобразование строки в логическое значение
s = input("Введите строку: ")

if s:                      # непустая строка -> True, пустая -> False
    print("Строка непустая, условие истинно")
else:
    print("Строка пустая, условие ложно")

# то же самое в явном виде
print(bool(s))

# преобразование работает и в логических операциях
print("" or "запасное значение")        # пустая строка ложна, берется второй операнд
print("abc" and "результат")            # непустая истинна, берется второй операнд
print(not "")                           # True

# важно: любая непустая строка истинна, даже "0" и "False"
print(bool("0"), bool("False"), bool(" "), bool(""))

# неявно строка превращается в bool, а bool потом в число
print(("a" and True) + 1)               # 2
