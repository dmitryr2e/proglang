#include <iostream>

int main() {
    std::cout << "=== Демонстрация 3 случаев использования токена '*' ===" << std::endl;

    // Случай 1: Описатель типа указателя при объявлении
    int val = 15;
    int *ptr = &val; // '*' специфицирует тип указателя на int
    std::cout << "1. Описатель указателя: int *ptr; -> адрес: " << ptr << std::endl;

    // Случай 2: Унарный оператор разыменования указателя
    *ptr = 42; // '*' разыменовывает ptr, перезаписывая значение val
    std::cout << "2. Разыменование указателя: *ptr = 42; -> val = " << val << std::endl;

    // Случай 3: Бинарный арифметический оператор умножения
    int a = 6, b = 7;
    int product = a * b; // '*' выполняет умножение
    std::cout << "3. Бинарное умножение: 6 * 7 = " << product << std::endl;

    std::cout << "\n=== Демонстрация 3 случаев использования токена '&' ===" << std::endl;

    // Случай 1: Унарный оператор взятия адреса
    int num = 100;
    int *pNum = &num; // '&' возвращает виртуальный адрес переменной num
    std::cout << "1. Взятие адреса: &num = " << pNum << std::endl;

    // Случай 2: Описатель ссылочного типа при объявлении
    int &ref = num; // '&' объявляет ref как ссылку на num
    ref = 200; // модифицирует переменную num через ссылку
    std::cout << "2. Описатель ссылки: int &ref = num; ref = 200; -> num = " << num << std::endl;

    // Случай 3: Бинарный побитовый оператор И (bitwise AND)
    int mask = 12;   // 0b1100
    int flags = 10;  // 0b1010
    int bitwise_res = mask & flags; // 0b1000 = 8
    std::cout << "3. Побитовое И: 12 & 10 = " << bitwise_res << std::endl;

    return 0;
}
