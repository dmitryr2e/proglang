#include <iostream>

int main() {
    int x[10][10] = {0};

    // Заполняем массив характерными значениями: x[i][j] = i * 100 + j
    for (int i = 0; i < 10; ++i) {
        for (int j = 0; j < 10; ++j) {
            x[i][j] = i * 100 + j;
        }
    }

    std::cout << "=== Демонстрация 1: Выход за границы столбцов (внутри выделенного блока) ===\n";
    std::cout << "Значение x[1][0]: " << x[1][0] << std::endl;
    std::cout << "Обращение через x[0][10]: " << x[0][10] << std::endl;
    std::cout << "Адрес &x[1][0]:  " << &x[1][0] << std::endl;
    std::cout << "Адрес &x[0][10]: " << &x[0][10] << " (адреса полностью совпадают!)\n\n";

    std::cout << "Модифицируем x[0][10] = 7777...\n";
    x[0][10] = 7777;
    std::cout << "Новое значение x[1][0]: " << x[1][0] << " (изменилось!)\n\n";

    std::cout << "=== Демонстрация 2: Отрицательный индекс столбца ===\n";
    std::cout << "Значение x[0][9]: " << x[0][9] << std::endl;
    std::cout << "Обращение через x[1][-1]: " << x[1][-1] << std::endl;
    std::cout << "Адрес &x[0][9]:  " << &x[0][9] << std::endl;
    std::cout << "Адрес &x[1][-1]: " << &x[1][-1] << " (адреса совпадают!)\n\n";

    std::cout << "=== Демонстрация 3: Выход за пределы последней строки массива ===\n";
    std::cout << "Элемент x[9][9] (последний легальный): адрес " << &x[9][9] << ", значение " << x[9][9] << "\n";
    std::cout << "Элемент x[10][0] (за границей массива): адрес " << &x[10][0] << ", значение " << x[10][0] << " (мусор из памяти стека)\n";
    std::cout << "По стандарту C++ выход за границы массива (UB) не проверяется компилятором автоматически.\n";
    std::cout << "При записи в x[10][0] или x[11][..] будут повреждены другие локальные переменные или стек вызова.\n";

    return 0;
}
