#include <iostream>
using namespace std;

// Исходные строки:
//   x = x + 1;
//   z = z + 2 * x + 3 * y;
//   y = y + 1;
// x увеличивается ДО использования в z, а y - ПОСЛЕ.
// Поэтому в вариантах с инкрементом: ++x (префиксный) и y++ (постфиксный).

int main() {
    int x, y, z;

    // Исходный вариант (для сравнения)
    x = 1; y = 2; z = 3;
    x = x + 1;
    z = z + 2 * x + 3 * y;
    y = y + 1;
    cout << "original: x=" << x << " y=" << y << " z=" << z << endl;

    // Способ 1: оператор запятая, без инкрементов
    x = 1; y = 2; z = 3;
    x = x + 1, z = z + 2 * x + 3 * y, y = y + 1;
    cout << "way 1:    x=" << x << " y=" << y << " z=" << z << endl;

    // Способ 2: оператор запятая и инкременты
    x = 1; y = 2; z = 3;
    ++x, z += 2 * x + 3 * y, y++;
    cout << "way 2:    x=" << x << " y=" << y << " z=" << z << endl;

    // Способ 3: один оператор присваивания, инкременты внутри
    x = 1; y = 2; z = 3;
    z += 2 * (++x) + 3 * (y++);
    cout << "way 3:    x=" << x << " y=" << y << " z=" << z << endl;

    // Способ 4: то же самое, но через z = z + ...
    x = 1; y = 2; z = 3;
    z = z + 2 * (++x) + 3 * (y++);
    cout << "way 4:    x=" << x << " y=" << y << " z=" << z << endl;

    return 0;
}
